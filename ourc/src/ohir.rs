pub enum H {
    CastH(Box<H>, String, u32),
    BreakH(u32),
    BreakNH(u32, u32),
    ContH(u32),
    ContNH(u32, u32),
    RetH(Box<H>, u32),
    StrH(String, u32),
    StoreIdxH(Box<H>, Box<H>, Box<H>, u32),
    StoreFieldH(Box<H>, u32, Box<H>, u32),
    ArrLitH(Vec<H>, u32),
    IndexH(Box<H>, Box<H>, u32),
    EnumLitH(u32, Vec<H>, u32),
    MatchH(Box<H>, Vec<HArm>, u32),
    StructLitH(u32, Vec<H>, u32),
    FieldH(Box<H>, u32, u32),
    WhileH(Box<H>, Box<H>, u32),
    SeqH(Box<H>, Box<H>, u32),
    AssignH(u32, Box<H>, u32),
    CallH(String, Vec<H>, u32),
    Lit(i64, u32),
    LitB(bool, u32),
    Local(u32, u32),
    BinH(String, Box<H>, Box<H>, u32),
    IfH(Box<H>, Box<H>, Box<H>, u32),
    LetH(u32, Box<H>, Box<H>, u32),
}
pub struct HArm {
    pub tag: i32,
    pub nbinds: u32,
    pub slots: Vec<u32>,
    pub body: H,
}
pub fn h_id(h: &H) -> u32 {
    match h {
        H::ContNH(_n, i) => *i,
        H::BreakNH(_n, i) => *i,
        H::CastH(_x, _t, i) => *i,
        H::BreakH(i) => *i,
        H::ContH(i) => *i,
        H::RetH(_x, i) => *i,
        H::StrH(_v, i) => *i,
        H::StoreIdxH(_b, _i, _v, i2) => *i2,
        H::StoreFieldH(_b, _f, _v, i2) => *i2,
        H::ArrLitH(_x, i) => *i,
        H::IndexH(_b, _x, i) => *i,
        H::EnumLitH(_t, _p, i) => *i,
        H::MatchH(_s, _a, i) => *i,
        H::StructLitH(_n, _f, i) => *i,
        H::FieldH(_b, _x, i) => *i,
        H::WhileH(_c, _b, i) => *i,
        H::SeqH(_a, _b, i) => *i,
        H::AssignH(_s, _v, i) => *i,
        H::CallH(_n, _a, i) => *i,
        H::Lit(_v, i) => *i,
        H::LitB(_v, i) => *i,
        H::Local(_s, i) => *i,
        H::BinH(_o, _a, _b, i) => *i,
        H::IfH(_c, _t, _f, i) => *i,
        H::LetH(_s, _v, _b, i) => *i,
    }
}
